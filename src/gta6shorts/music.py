"""Original background music and sound effects, synthesised from scratch.

Because every note is generated by this code, the channel owns it outright —
no licensing, no Content ID claims. Each video gets its own tempo, key,
chord progression and arrangement (seeded), so tracks don't repeat.

Licensed library tracks are also supported, but ONLY when they are listed
with their licence in assets/music/licenses.yaml (see load_library()).
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import soundfile as sf
import yaml

SR = 48000

# chord roots relative to the key (natural minor): i–VI–III–VII etc.
PROGRESSIONS = [
    [(0, "m"), (8, "M"), (3, "M"), (10, "M")],
    [(0, "m"), (5, "m"), (8, "M"), (7, "m")],
    [(0, "m"), (10, "M"), (8, "M"), (10, "M")],
    [(0, "m"), (8, "M"), (5, "m"), (7, "M")],
]


def midi_hz(n: float) -> float:
    return 440.0 * 2 ** ((n - 69) / 12)


def smooth(x: np.ndarray, k: int) -> np.ndarray:
    """Cheap moving-average low-pass filter."""
    if k <= 1:
        return x
    return np.convolve(x, np.ones(k, dtype=np.float32) / k, mode="same")


def env_exp(n: int, decay_s: float, sr: int = SR) -> np.ndarray:
    t = np.arange(n, dtype=np.float32) / sr
    return np.exp(-t / max(decay_s, 1e-3)).astype(np.float32)


def saw_additive(freq: float, n: int, harmonics: int = 10, sr: int = SR, phase: float = 0.0) -> np.ndarray:
    t = np.arange(n, dtype=np.float32) / sr
    out = np.zeros(n, dtype=np.float32)
    for k in range(1, harmonics + 1):
        if freq * k > sr / 2.2:
            break
        out += np.sin(2 * np.pi * freq * k * t + phase * k) / k * (0.92 ** k)
    return out


def add_at(track: np.ndarray, sound: np.ndarray, start: int) -> None:
    if start >= len(track):
        return
    end = min(len(track), start + len(sound))
    track[start:end] += sound[: end - start]


@dataclass
class TrackInfo:
    bpm: int
    key: int
    progression: int
    seed: int


def synth_track(duration: float, seed: int = 0, sr: int = SR) -> tuple[np.ndarray, TrackInfo]:
    """Stereo synthwave-style loop (float32, shape (n, 2), peak ≈ -1 dBFS)."""
    rng = np.random.default_rng(seed)
    bpm = int(rng.choice([96, 100, 104, 108, 112, 116]))
    key = int(rng.integers(45, 52))  # A2..D#3
    prog_idx = int(rng.integers(0, len(PROGRESSIONS)))
    prog = PROGRESSIONS[prog_idx]
    beat = 60.0 / bpm
    bar = beat * 4
    n = int((duration + 0.5) * sr)
    drums = np.zeros(n, dtype=np.float32)
    bass = np.zeros(n, dtype=np.float32)
    pad_l = np.zeros(n, dtype=np.float32)
    pad_r = np.zeros(n, dtype=np.float32)
    arp_l = np.zeros(n, dtype=np.float32)
    arp_r = np.zeros(n, dtype=np.float32)
    duck = np.ones(n, dtype=np.float32)

    # one-shot drum sounds
    kn = int(0.35 * sr)
    tk = np.arange(kn, dtype=np.float32) / sr
    kick_f = 45 + 95 * np.exp(-tk / 0.03)
    kick = np.sin(2 * np.pi * np.cumsum(kick_f) / sr) * env_exp(kn, 0.16)
    sn = int(0.22 * sr)
    noise = rng.standard_normal(sn).astype(np.float32)
    snare = (smooth(noise, 3) - smooth(noise, 24)) * env_exp(sn, 0.07) * 0.7
    snare += np.sin(2 * np.pi * 190 * np.arange(sn) / sr).astype(np.float32) * env_exp(sn, 0.05) * 0.5
    hn = int(0.05 * sr)
    hnoise = rng.standard_normal(hn).astype(np.float32)
    hat = (hnoise - smooth(hnoise, 4)) * env_exp(hn, 0.012) * 0.35
    pump = 1 - 0.55 * env_exp(int(beat * sr), beat * 0.35)

    four_on_floor = rng.random() < 0.5
    hat_16 = rng.random() < 0.5
    arp_pattern = rng.choice([[0, 1, 2, 1], [0, 2, 1, 2], [0, 1, 2, 3], [2, 1, 0, 1]])
    n_bars = int(np.ceil(duration / bar)) + 1

    for b in range(n_bars):
        root_off, quality = prog[b % len(prog)]
        root = key + root_off
        third = 3 if quality == "m" else 4
        chord = [root, root + third, root + 7, root + 12]
        bar_start = int(b * bar * sr)
        # drums
        for q in range(4):
            pos = bar_start + int(q * beat * sr)
            if q in (0, 2) or four_on_floor:
                add_at(drums, kick * 0.9, pos)
                end = min(n, pos + len(pump))
                if pos < n:
                    duck[pos:end] = np.minimum(duck[pos:end], pump[: end - pos])
            if q in (1, 3):
                add_at(drums, snare, pos)
        steps = 16 if hat_16 else 8
        for s in range(steps):
            vel = 0.55 + 0.45 * (s % 2 == 0)
            add_at(drums, hat * vel, bar_start + int(s * bar / steps * sr))
        # bass: eighth notes on the root
        bn = int(beat / 2 * sr)
        for e in range(8):
            f = midi_hz(root - 12 + (12 if e in (3, 7) and rng.random() < 0.4 else 0))
            note = saw_additive(f, bn, harmonics=6) * env_exp(bn, 0.18) * 0.55
            add_at(bass, note, bar_start + e * bn)
        # pad: sustained chord, slow attack, detuned stereo
        pn = int(bar * sr)
        att = np.clip(np.arange(pn) / (0.25 * sr), 0, 1).astype(np.float32)
        rel = np.clip((pn - np.arange(pn)) / (0.15 * sr), 0, 1).astype(np.float32)
        for note in chord[:3]:
            f = midi_hz(note + 12)
            add_at(pad_l, saw_additive(f * 0.997, pn, 5) * att * rel * 0.12, bar_start)
            add_at(pad_r, saw_additive(f * 1.003, pn, 5, phase=0.7) * att * rel * 0.12, bar_start)
        # arp: sixteenth notes, two octaves up, ping-pong panned
        an = int(beat / 4 * sr)
        for s in range(16):
            note = chord[arp_pattern[s % 4]] + 24
            pluck = saw_additive(midi_hz(note), an, harmonics=4) * env_exp(an, 0.06) * 0.16
            target = arp_l if s % 2 == 0 else arp_r
            add_at(target, pluck, bar_start + s * an)

    # echo on the arp (dotted eighth), and side-chain "pump" on pad & bass
    d = int(beat * 0.75 * sr)
    arp_l[d:] += arp_r[:-d] * 0.35
    arp_r[d:] += arp_l[:-d] * 0.35
    bass *= duck
    pad_l *= duck
    pad_r *= duck
    left = drums * 0.8 + bass + pad_l + arp_l
    right = drums * 0.8 + bass + pad_r + arp_r
    stereo = np.stack([left, right], axis=1)[: int(duration * sr)]
    stereo = np.tanh(stereo * 1.2)  # gentle saturation / soft clip
    fade_in = np.clip(np.arange(len(stereo)) / (0.03 * sr), 0, 1)[:, None]
    fade_out = np.clip((len(stereo) - np.arange(len(stereo))) / (1.2 * sr), 0, 1)[:, None]
    stereo = stereo * fade_in * fade_out
    peak = float(np.max(np.abs(stereo))) or 1.0
    stereo = (stereo / peak * 0.89).astype(np.float32)
    return stereo, TrackInfo(bpm, key, prog_idx, seed)


# ── Sound effects ────────────────────────────────────────────────────────────
def sfx_whoosh(seed: int = 0, sr: int = SR) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = int(0.45 * sr)
    noise = rng.standard_normal(n).astype(np.float32)
    t = np.linspace(0, 1, n, dtype=np.float32)
    bright = noise - smooth(noise, 6)
    dark = smooth(noise, 18)
    sweep = dark * (1 - t) + bright * t
    shape = np.sin(np.pi * t) ** 2
    mono = sweep * shape * 0.5
    pan = t[:, None]
    return np.concatenate([mono[:, None] * (1 - pan), mono[:, None] * pan], axis=1)


def sfx_impact(seed: int = 0, sr: int = SR) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = int(0.9 * sr)
    t = np.arange(n, dtype=np.float32) / sr
    f = 32 + 70 * np.exp(-t / 0.08)
    boom = np.sin(2 * np.pi * np.cumsum(f) / sr) * env_exp(n, 0.35)
    noise = smooth(rng.standard_normal(n).astype(np.float32), 10) * env_exp(n, 0.06) * 1.5
    mono = np.tanh((boom + noise) * 1.6) * 0.7
    return np.stack([mono, mono], axis=1)


def sfx_pop(sr: int = SR) -> np.ndarray:
    n = int(0.09 * sr)
    t = np.arange(n, dtype=np.float32) / sr
    f = 950 - 380 * t / t[-1]
    mono = np.sin(2 * np.pi * np.cumsum(f) / sr) * env_exp(n, 0.025) * 0.35
    return np.stack([mono, mono], axis=1)


def build_sfx_track(duration: float, impacts: list[float], whooshes: list[float], pops: list[float],
                    seed: int = 0, sr: int = SR) -> np.ndarray:
    track = np.zeros((int(duration * sr), 2), dtype=np.float32)

    def place(sound: np.ndarray, at: float) -> None:
        start = max(0, int(at * sr))
        end = min(len(track), start + len(sound))
        if end > start:
            track[start:end] += sound[: end - start]

    for t in impacts:
        place(sfx_impact(seed), t)
    for i, t in enumerate(whooshes):
        place(sfx_whoosh(seed + i), t)
    for t in pops:
        place(sfx_pop(), t)
    return track


# ── Licensed library (optional) ──────────────────────────────────────────────
REQUIRED_LICENSE_FIELDS = ("file", "title", "artist", "license", "source_url")


def load_library(manifest: Path) -> list[dict]:
    """Return only tracks that exist AND carry complete licence information."""
    if not manifest.exists():
        return []
    entries = (yaml.safe_load(manifest.read_text(encoding="utf-8")) or {}).get("tracks") or []
    usable = []
    for e in entries:
        if all(e.get(k) for k in REQUIRED_LICENSE_FIELDS) and (manifest.parent / e["file"]).exists():
            usable.append(e)
    return usable


def write_wav(path: Path, audio: np.ndarray, sr: int = SR) -> Path:
    sf.write(str(path), audio, sr, subtype="PCM_16")
    return path
